// Regenerate src/compiler/builtins-table.ts from the runtime: the names
// and arities of the builtins, and which are in the global scope. The
// compiler reads the table rather than the runtime so that it has no
// dependency on node and can run in a browser.
//
//   node tools/gen-builtins-table.ts
import { writeFileSync } from "node:fs";
import { GLOBALS, builtins } from "../src/runtime/builtins.ts";
import { isPrimOp } from "../src/runtime/value.ts";

const entries: string[] = [];
for (const name of Object.keys(builtins).sort()) {
  const v = builtins[name];
  const arity =
    typeof v === "function" && isPrimOp(v)
      ? v.arity
      : typeof v === "function"
        ? 1
        : 0;
  entries.push(`  [${JSON.stringify(name)}, ${arity}],`);
}
const out = `// Generated by tools/gen-builtins-table.ts from src/runtime/builtins.ts.
// Do not edit: rerun the tool when a builtin is added.

// Every builtin and its arity; a constant has arity 0.
export const BUILTIN_ARITY: ReadonlyMap<string, number> = new Map([
${entries.join("\n")}
]);

// Names Nix puts in the global scope without the \`builtins.\` prefix.
export const GLOBALS: ReadonlySet<string> = new Set(${JSON.stringify([...GLOBALS].sort(), null, 2)});
`;
writeFileSync(
  new URL("../src/compiler/builtins-table.ts", import.meta.url),
  out,
);
console.log(`wrote ${entries.length} builtins`);
