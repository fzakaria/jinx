#!/usr/bin/env bash
# Build the jinx-nixpkgs tree: nixpkgs at one revision, compiled with the
# runtime vendored in, plus the metadata a consumer needs to pair it with
# the source tree (docs/tracking-nixpkgs.md).
#
#   tools/publish-nixpkgs.sh <rev> <out-dir>
#
# <rev> is a nixpkgs commit; the source is fetched by nix and never copied
# into the tree. The consumer places or symlinks a checkout of that commit
# at <out-dir>/nixpkgs, which is what .jinx/config.json names.
set -euo pipefail

rev=${1:?usage: publish-nixpkgs.sh <rev> <out-dir>}
out=${2:?usage: publish-nixpkgs.sh <rev> <out-dir>}
here="$(cd "$(dirname "$0")/.." && pwd)"

meta=$(nix flake prefetch "github:NixOS/nixpkgs/$rev" --json)
src=$(jq -r .storePath <<<"$meta")
narHash=$(jq -r .hash <<<"$meta")
fullRev=$(jq -r '.locked.rev // empty' <<<"$meta")
if [ -z "$fullRev" ]; then
  fullRev=$rev
fi

mkdir -p "$out"
ulimit -s unlimited 2>/dev/null || true
node --disable-warning=ExperimentalWarning --stack-size=1000000 "$here/src/cli/main.ts" compile "$src" --out "$out" --vendor-runtime

# The config names the source tree relative to the output tree, and
# records the revision so a consumer can fetch exactly that source.
jinxCommit=$(cd "$here" && (jj log -r @- --no-graph -T commit_id 2>/dev/null || git rev-parse HEAD))
cat > "$out/.jinx/config.json" <<JSON
{
  "srcRoot": "./nixpkgs",
  "nixpkgs": {
    "rev": "$fullRev",
    "narHash": "$narHash",
    "url": "github:NixOS/nixpkgs/$fullRev"
  },
  "jinx": "$jinxCommit"
}
JSON
ln -sfn "$src" "$out/nixpkgs"

cat > "$out/README.md" <<'MD'
# jinx-nixpkgs

nixpkgs, transpiled to TypeScript by [jinx](https://github.com/fzakaria/jinx).

Every `.nix` file of one nixpkgs revision is here as a `.ts` module in the
same place in the tree, with a source map beside it pointing back at the
Nix. `.jinx/config.json` names the revision; `.jinx/runtime/` is the jinx
runtime the modules import, so the tree stands alone.

The Nix source tree is not in this repository. Put a checkout of the
revision in `.jinx/config.json` at `./nixpkgs` (a symlink is fine); the
modules read patches, scripts and `pkgs/by-name` from it:

```console
$ rev=$(jq -r .nixpkgs.rev .jinx/config.json)
$ ln -s "$(nix flake prefetch github:NixOS/nixpkgs/$rev --json | jq -r .storePath)" nixpkgs
$ node --stack-size=1000000 ../jinx/src/cli/main.ts eval ./nixpkgs -A hello --tree .
```

Or evaluate from TypeScript with jinx's view API:

```ts
import { loadNixpkgs } from "jinx";
const pkgs = loadNixpkgs("./nixpkgs", { tree: "." });
console.log(pkgs.hello.drvPath);
```

Regenerated by `tools/publish-nixpkgs.sh` in the jinx repository, one commit
per tracked nixpkgs revision. nixpkgs is MIT; so is this.
MD
printf 'nixpkgs\n' > "$out/.gitignore"
echo "wrote $out for nixpkgs $fullRev"
